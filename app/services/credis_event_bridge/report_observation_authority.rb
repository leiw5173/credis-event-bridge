# frozen_string_literal: true

module CredisEventBridge
  class ReportObservationAuthority
    APPEND_BODY = <<~SQL
      DECLARE r reviewables%ROWTYPE;
      BEGIN
        IF NEW.observed_at IS NOT NULL OR NEW.latest_evidence_id IS NOT NULL OR NEW.core_snapshot IS NOT NULL THEN
          RAISE EXCEPTION 'Report observation is generated by the source guard' USING ERRCODE='check_violation';
        END IF;
        IF NOT EXISTS(SELECT 1 FROM credis_capture_epochs WHERE baseline_complete
          AND status IN ('collecting','closed') AND compatibility_token=NEW.compatibility_token) THEN
          RAISE EXCEPTION 'Report observation pin has no certified epoch' USING ERRCODE='check_violation';
        END IF;
        PERFORM pg_advisory_xact_lock(hashtextextended('credis-report-source',0));
        SELECT * INTO r FROM reviewables WHERE id=NEW.reviewable_id FOR SHARE;
        IF FOUND AND (r.type<>'ReviewableFlaggedPost' OR r.target_type<>'Post') THEN
          RAISE EXCEPTION 'Report observation has another Reviewable type' USING ERRCODE='check_violation';
        END IF;
        PERFORM id FROM posts WHERE id=r.target_id FOR SHARE;
        PERFORM id FROM flags ORDER BY id FOR SHARE;
        PERFORM id FROM reviewable_scores WHERE reviewable_id=NEW.reviewable_id ORDER BY id FOR SHARE;
        PERFORM id FROM reviewable_histories WHERE reviewable_id=NEW.reviewable_id ORDER BY id FOR SHARE;
        PERFORM id FROM post_actions WHERE post_id=r.target_id ORDER BY id FOR SHARE;
        SELECT id INTO NEW.latest_evidence_id FROM credis_report_evidence
          WHERE reviewable_id=NEW.reviewable_id ORDER BY revision DESC LIMIT 1 FOR SHARE;
        NEW.observed_at:=clock_timestamp() AT TIME ZONE 'UTC';
        NEW.core_snapshot:=credis_report_core_snapshot(NEW.reviewable_id);
        RETURN NEW;
      END;
    SQL

    IMMUTABLE_BODY = <<~SQL
      BEGIN
        RAISE EXCEPTION 'Report observation fences are immutable' USING ERRCODE='check_violation';
      END;
    SQL

    ROOT = File.expand_path("../../..", __dir__).freeze
    SOURCE_FILES = %w[
      app/models/credis_report_observation_fence.rb
      app/controllers/credis_event_bridge/report_observations_controller.rb
      app/services/credis_event_bridge/report_observation.rb
      app/services/credis_event_bridge/report_observation_authority.rb
      db/migrate/20261001000018_create_credis_report_observation_fences.rb
      config/routes.rb
    ].freeze
    SOURCE_DIGESTS = SOURCE_FILES.to_h { |path| [path, Digest::SHA256.file(File.join(ROOT, path)).hexdigest] }.freeze

    class << self
      def verify_installed!
        return true if !ReportSource::ENABLED

        SOURCE_DIGESTS.each do |path, digest|
          raise SourceCompatibility::Error, "Report observation implementation changed" if
            Digest::SHA256.file(File.join(ROOT, path)).hexdigest != digest
        end
        connection = ActiveRecord::Base.connection
        expected = {
          "certify_credis_report_observation" => APPEND_BODY,
          "protect_credis_report_observation" => IMMUTABLE_BODY,
        }
        functions = connection.select_all(<<~SQL).to_a
          SELECT p.proname,p.prosrc FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace
          WHERE n.nspname=current_schema() AND p.proname IN (
            'certify_credis_report_observation','protect_credis_report_observation')
        SQL
        unless functions.length == expected.length && functions.all? { |f| f["prosrc"].strip == expected.fetch(f["proname"]).strip }
          raise SourceCompatibility::Error, "unsupported Report observation functions"
        end
        columns = connection.select_all(<<~SQL).to_a
          SELECT attname,atttypid::regtype::text AS type,attnotnull AS required
          FROM pg_attribute WHERE attrelid='credis_report_observation_fences'::regclass
          AND attnum>0 AND NOT attisdropped ORDER BY attname
        SQL
        expected_columns = [
          ["compatibility_token", "character varying", true], ["core_snapshot", "jsonb", true],
          ["fence_id", "uuid", true], ["latest_evidence_id", "bigint", false],
          ["observed_at", "timestamp without time zone", true], ["reviewable_id", "bigint", true],
        ]
        unless columns.map { |c| [c["attname"], c["type"], c["required"]] } == expected_columns
          raise SourceCompatibility::Error, "unsupported Report observation columns"
        end
        triggers = connection.select_all(<<~SQL).to_a
          SELECT t.tgname,t.tgtype,p.proname FROM pg_trigger t JOIN pg_proc p ON p.oid=t.tgfoid
          WHERE t.tgrelid='credis_report_observation_fences'::regclass AND NOT t.tgisinternal AND t.tgenabled='O'
        SQL
        unless triggers.map { |t| [t["tgname"], t["tgtype"], t["proname"]] }.sort == [
          ["credis_report_observation_append", 7, "certify_credis_report_observation"],
          ["credis_report_observation_immutable", 27, "protect_credis_report_observation"],
          ["credis_report_observation_no_truncate", 34, "protect_credis_report_observation"],
        ].sort
          raise SourceCompatibility::Error, "unsupported Report observation triggers"
        end
        true
      rescue ActiveRecord::StatementInvalid
        raise SourceCompatibility::Error, "Report observation guards unavailable"
      end
    end
  end
end
