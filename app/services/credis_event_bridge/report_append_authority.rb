module CredisEventBridge
  class ReportAppendAuthority
    # Captures identities and states only. Report text, reasons and Post bodies
    # are deliberately absent. SQL and executed migration bodies are immutable.
    SNAPSHOT_BODY = <<~SQL
      SELECT jsonb_build_object(
        'reviewable',(SELECT jsonb_build_object('id',r.id,'type',r.type,
          'target_id',r.target_id,'target_type',r.target_type,'topic_id',r.topic_id,
          'target_created_by_id',r.target_created_by_id,'status',r.status,
          'version',r.version,'created_at',r.created_at,'updated_at',r.updated_at)
          FROM reviewables r WHERE r.id=reviewable_key),
        'scores',COALESCE((SELECT jsonb_agg(jsonb_build_object('id',s.id,
          'reviewable_id',s.reviewable_id,'user_id',s.user_id,
          'reviewable_score_type',s.reviewable_score_type,'status',s.status,
          'reviewed_by_id',s.reviewed_by_id,'reviewed_at',s.reviewed_at,
          'created_at',s.created_at,'updated_at',s.updated_at) ORDER BY s.id)
          FROM reviewable_scores s WHERE s.reviewable_id=reviewable_key),'[]'::jsonb),
        'histories',COALESCE((SELECT jsonb_agg(jsonb_build_object('id',h.id,
          'reviewable_id',h.reviewable_id,'created_by_id',h.created_by_id,
          'reviewable_history_type',h.reviewable_history_type,'status',h.status,
          'created_at',h.created_at) ORDER BY h.id)
          FROM reviewable_histories h WHERE h.reviewable_id=reviewable_key),'[]'::jsonb),
        'post_actions',COALESCE((SELECT jsonb_agg(jsonb_build_object('id',a.id,
          'post_id',a.post_id,'user_id',a.user_id,'post_action_type_id',a.post_action_type_id,
          'created_at',a.created_at,'deleted_at',a.deleted_at,
          'agreed_at',a.agreed_at,'agreed_by_id',a.agreed_by_id,
          'disagreed_at',a.disagreed_at,'disagreed_by_id',a.disagreed_by_id,
          'deferred_at',a.deferred_at,'deferred_by_id',a.deferred_by_id) ORDER BY a.id)
          FROM post_actions a JOIN reviewables r ON r.target_id=a.post_id
          JOIN flags f ON f.id=a.post_action_type_id AND f.notify_type
          WHERE r.id=reviewable_key AND r.target_type='Post'),'[]'::jsonb),
        'post',(SELECT jsonb_build_object('id',p.id,'topic_id',p.topic_id,'user_id',p.user_id,
          'post_number',p.post_number,'post_type',p.post_type,'version',p.version,
          'deleted_at',p.deleted_at,'hidden',p.hidden,'user_deleted',p.user_deleted)
          FROM posts p JOIN reviewables r ON r.target_id=p.id
          WHERE r.id=reviewable_key AND r.target_type='Post'),
        'flags',COALESCE((SELECT jsonb_agg(jsonb_build_object('id',f.id,'name_key',f.name_key,
          'notify_type',f.notify_type,'score_type',f.score_type,'enabled',f.enabled,
          'applies_to',f.applies_to) ORDER BY f.id) FROM flags f),'[]'::jsonb))
    SQL

    APPEND_BODY = <<~SQL
      DECLARE
        r reviewables%ROWTYPE;
        u users%ROWTYPE;
        e credis_capture_epochs%ROWTYPE;
        previous credis_report_evidence%ROWTYPE;
      BEGIN
        IF NEW.source_snapshot IS NOT NULL THEN
          RAISE EXCEPTION 'Report snapshot is generated by the source guard' USING ERRCODE='check_violation';
        END IF;
        SELECT * INTO r FROM reviewables WHERE id=NEW.reviewable_id FOR UPDATE;
        IF NOT FOUND OR r.type<>'ReviewableFlaggedPost' OR r.target_type<>'Post' THEN
          RAISE EXCEPTION 'Report Reviewable identity unavailable' USING ERRCODE='check_violation';
        END IF;
        PERFORM id FROM flags ORDER BY id FOR SHARE;
        PERFORM id FROM reviewable_scores WHERE reviewable_id=r.id ORDER BY id FOR SHARE;
        PERFORM id FROM reviewable_histories WHERE reviewable_id=r.id ORDER BY id FOR SHARE;
        PERFORM id FROM post_actions WHERE post_id=r.target_id ORDER BY id FOR SHARE;
        PERFORM id FROM posts WHERE id=r.target_id FOR SHARE;
        SELECT * INTO u FROM users WHERE id=NEW.operator_user_id FOR SHARE;
        IF NOT FOUND OR (u.id<=0 AND u.id<>-1) THEN
          RAISE EXCEPTION 'Report operator identity unavailable' USING ERRCODE='check_violation';
        END IF;
        SELECT * INTO e FROM credis_capture_epochs WHERE epoch_id=NEW.epoch_id FOR SHARE;
        IF NOT FOUND OR e.status<>'collecting' OR e.baseline_complete IS NOT TRUE OR e.compatibility_token IS NULL THEN
          RAISE EXCEPTION 'Report capture epoch unavailable' USING ERRCODE='check_violation';
        END IF;
        SELECT * INTO previous FROM credis_report_evidence WHERE reviewable_id=r.id ORDER BY revision DESC LIMIT 1;
        IF (previous.id IS NULL AND (NEW.revision<>1 OR NEW.previous_evidence_id IS NOT NULL))
          OR (previous.id IS NOT NULL AND (NEW.revision<>previous.revision+1 OR NEW.previous_evidence_id IS DISTINCT FROM previous.id)) THEN
          RAISE EXCEPTION 'Report predecessor differs' USING ERRCODE='check_violation';
        END IF;
        NEW.occurred_at:=clock_timestamp();
        IF NEW.occurred_at<e.started_at THEN
          RAISE EXCEPTION 'Report append precedes capture epoch' USING ERRCODE='check_violation';
        END IF;
        NEW.source_snapshot:=jsonb_build_object('schema_version',1,'entry',to_jsonb(NEW)-'source_snapshot',
          'operator',jsonb_build_object('id',u.id,'admin',u.admin,'moderator',u.moderator),
          'epoch',jsonb_build_object('id',e.epoch_id,'started_at',e.started_at,'compatibility_token',e.compatibility_token),
          'core',credis_report_core_snapshot(r.id));
        RETURN NEW;
      END;
    SQL

    IMMUTABLE_BODY = <<~SQL
      BEGIN
        RAISE EXCEPTION 'Report source evidence is immutable' USING ERRCODE='check_violation';
      END;
    SQL

    IMPLEMENTATION_FILES = %w[
      app/models/credis_report_evidence.rb
      app/services/credis_event_bridge/report_source.rb
      app/services/credis_event_bridge/report_append_authority.rb
      db/migrate/20261001000015_create_credis_report_evidence.rb
    ].freeze
    ROOT = File.expand_path("../../..", __dir__).freeze
    SOURCE_DIGESTS = IMPLEMENTATION_FILES.to_h { |path| [path, Digest::SHA256.file(File.join(ROOT, path)).hexdigest] }.freeze

    class << self
      def verify_installed!
        return true if !ReportSource::ENABLED

        connection = ActiveRecord::Base.connection
        expected = {
          "credis_report_core_snapshot" => SNAPSHOT_BODY,
          "certify_credis_report_append" => APPEND_BODY,
          "protect_credis_report_evidence" => IMMUTABLE_BODY,
        }
        functions = connection.select_all(<<~SQL).to_a
          SELECT p.proname,p.prosrc FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace
          WHERE n.nspname=current_schema() AND p.proname IN (
            'credis_report_core_snapshot','certify_credis_report_append','protect_credis_report_evidence')
        SQL
        unless functions.length == expected.length && functions.all? { |f| f["prosrc"].strip == expected.fetch(f["proname"]).strip }
          raise SourceCompatibility::Error, "unsupported Report guard functions"
        end
        triggers = connection.select_all(<<~SQL).to_a
          SELECT t.tgname,t.tgtype,p.proname FROM pg_trigger t JOIN pg_proc p ON p.oid=t.tgfoid
          WHERE t.tgrelid='credis_report_evidence'::regclass AND NOT t.tgisinternal AND t.tgenabled='O'
        SQL
        unless triggers.map { |t| [t["tgname"], t["tgtype"], t["proname"]] }.sort == [
          ["credis_report_append_authority", 7, "certify_credis_report_append"],
          ["credis_report_evidence_immutable", 27, "protect_credis_report_evidence"],
          ["credis_report_evidence_no_truncate", 34, "protect_credis_report_evidence"],
        ].sort
          raise SourceCompatibility::Error, "unsupported Report guard triggers"
        end
        true
      rescue ActiveRecord::StatementInvalid
        raise SourceCompatibility::Error, "Report source migration unavailable"
      end
    end
  end
