# frozen_string_literal: true

module CredisEventBridge
  class DemoFormAppendAuthority
    # Immutable source contract. A later guard change needs a new migration.
    SQL_BODY = <<~SQL
      DECLARE
        p posts%ROWTYPE;
        t topics%ROWTYPE;
        c categories%ROWTYPE;
        u users%ROWTYPE;
        f form_templates%ROWTYPE;
        e credis_capture_epochs%ROWTYPE;
        previous credis_demo_form_evidence%ROWTYPE;
        submission credis_demo_form_evidence%ROWTYPE;
        binding_fields text[] := ARRAY['post_id','topic_id','author_user_id','category_id',
          'form_template_id','field_key','field_value','template_sha256','post_version','post_raw_sha256'];
        binding_field text;
      BEGIN
        IF NEW.append_authority IS NOT NULL THEN
          RAISE EXCEPTION 'Demo append authority is generated by the source guard' USING ERRCODE = 'check_violation';
        END IF;
        SELECT * INTO p FROM posts WHERE id=NEW.post_id FOR UPDATE;
        IF NOT FOUND THEN RAISE EXCEPTION 'Demo source Post unavailable' USING ERRCODE = 'check_violation'; END IF;
        SELECT * INTO t FROM topics WHERE id=p.topic_id FOR SHARE;
        IF NOT FOUND THEN RAISE EXCEPTION 'Demo source Topic unavailable' USING ERRCODE = 'check_violation'; END IF;
        SELECT * INTO c FROM categories WHERE id=t.category_id FOR SHARE;
        IF NOT FOUND THEN RAISE EXCEPTION 'Demo source category unavailable' USING ERRCODE = 'check_violation'; END IF;
        SELECT * INTO u FROM users WHERE id=NEW.actor_user_id FOR UPDATE;
        IF NOT FOUND OR u.admin IS DISTINCT FROM NEW.actor_is_admin THEN
          RAISE EXCEPTION 'Demo source actor role differs' USING ERRCODE = 'check_violation';
        END IF;
        IF p.post_number<>1 OR p.post_type<>1 OR p.deleted_at IS NOT NULL OR COALESCE(p.hidden,FALSE)
          OR COALESCE(p.user_deleted,FALSE) OR t.deleted_at IS NOT NULL OR t.visible IS NOT TRUE
          OR t.archetype<>'regular' OR c.read_restricted IS NOT FALSE
          OR NEW.topic_id<>p.topic_id OR NEW.author_user_id<>p.user_id OR NEW.category_id<>c.id
          OR NEW.post_version<>p.version OR p.raw IS NULL
          OR NEW.post_raw_sha256<>encode(sha256(convert_to(p.raw,'UTF8')),'hex') THEN
          RAISE EXCEPTION 'Demo source Post binding differs' USING ERRCODE = 'check_violation';
        END IF;
        SELECT * INTO f FROM form_templates WHERE id=NEW.form_template_id FOR SHARE;
        IF NOT FOUND OR octet_length(f.template)>65536 OR NEW.template_sha256<>encode(sha256(convert_to(f.template,'UTF8')),'hex') THEN
          RAISE EXCEPTION 'Demo source template differs' USING ERRCODE = 'check_violation';
        END IF;
        PERFORM id FROM category_form_templates WHERE category_id=c.id AND form_template_id=f.id FOR SHARE;
        IF NOT FOUND THEN RAISE EXCEPTION 'Demo source assignment unavailable' USING ERRCODE = 'check_violation'; END IF;
        SELECT * INTO e FROM credis_capture_epochs WHERE epoch_id=NEW.epoch_id FOR SHARE;
        IF NOT FOUND OR e.status<>'collecting' OR e.baseline_complete IS NOT TRUE OR e.compatibility_token IS NULL THEN
          RAISE EXCEPTION 'Demo source epoch unavailable' USING ERRCODE = 'check_violation';
        END IF;
        SELECT * INTO previous FROM credis_demo_form_evidence WHERE post_id=p.id ORDER BY revision DESC LIMIT 1;
        IF (previous.id IS NULL AND (NEW.revision<>1 OR NEW.previous_evidence_id IS NOT NULL))
          OR (previous.id IS NOT NULL AND (NEW.revision<>previous.revision+1 OR NEW.previous_evidence_id IS DISTINCT FROM previous.id)) THEN
          RAISE EXCEPTION 'Demo source predecessor differs' USING ERRCODE = 'check_violation';
        END IF;
        IF NEW.entry_kind='submission' THEN
          IF NEW.actor_user_id<>p.user_id OR NEW.state_code<>'pending' OR NEW.submission_evidence_id IS NOT NULL
            OR NEW.reason<>'form_submitted' THEN
            RAISE EXCEPTION 'Demo source submission authority differs' USING ERRCODE = 'check_violation';
          END IF;
        ELSIF NEW.entry_kind='review' THEN
          SELECT * INTO submission FROM credis_demo_form_evidence WHERE id=NEW.submission_evidence_id;
          IF NOT FOUND OR u.admin IS NOT TRUE OR submission.entry_kind<>'submission' OR previous.id IS NULL
            OR NEW.state_code NOT IN ('valid','revoked')
            OR NEW.submission_evidence_id IS DISTINCT FROM (CASE WHEN previous.entry_kind='submission' THEN previous.id ELSE previous.submission_evidence_id END) THEN
            RAISE EXCEPTION 'Demo source review authority differs' USING ERRCODE = 'check_violation';
          END IF;
          FOREACH binding_field IN ARRAY binding_fields LOOP
            IF to_jsonb(NEW)->binding_field IS DISTINCT FROM to_jsonb(submission)->binding_field THEN
              RAISE EXCEPTION 'Demo source reviewed submission differs' USING ERRCODE = 'check_violation';
            END IF;
          END LOOP;
        ELSE
          RAISE EXCEPTION 'Demo source entry kind differs' USING ERRCODE = 'check_violation';
        END IF;
        NEW.occurred_at := clock_timestamp();
        IF NEW.occurred_at<e.started_at THEN
          RAISE EXCEPTION 'Demo source append precedes its epoch' USING ERRCODE = 'check_violation';
        END IF;
        NEW.append_authority := jsonb_build_object(
          'schema_version',1,
          'entry',to_jsonb(NEW)-'append_authority',
          'actor',jsonb_build_object('id',u.id,'admin',u.admin),
          'post',jsonb_build_object('id',p.id,'topic_id',p.topic_id,'author_user_id',p.user_id,
            'category_id',c.id,'post_number',p.post_number,'post_type',p.post_type,'post_version',p.version,
            'content_status','eligible','raw_sha256',NEW.post_raw_sha256),
          'template',jsonb_build_object('id',f.id,'definition',f.template,'sha256',NEW.template_sha256),
          'assignment',jsonb_build_object('category_id',c.id,'form_template_id',f.id),
          'epoch',jsonb_build_object('id',e.epoch_id,'status',e.status,'baseline_complete',e.baseline_complete,
            'compatibility_token',e.compatibility_token,'started_at',e.started_at));
        RETURN NEW;
      END;
    SQL

    IMPLEMENTATION_FILES = %w[
      app/services/credis_event_bridge/demo_form_source.rb
      app/services/credis_event_bridge/demo_form_append_authority.rb
      db/migrate/20261001000014_add_credis_demo_append_authority.rb
    ].freeze
    ROOT = File.expand_path("../../..", __dir__).freeze
    SOURCE_DIGESTS = IMPLEMENTATION_FILES.to_h { |path| [path, Digest::SHA256.file(File.join(ROOT, path)).hexdigest] }.freeze

    class << self
      def verify_source!
        return true if !DemoFormSource::ENABLED
        SOURCE_DIGESTS.each do |path, expected|
          raise SourceCompatibility::Error, "Demo authority source changed" if Digest::SHA256.file(File.join(ROOT, path)).hexdigest != expected
        end
        true
      end

      def verify_installed!
        return true if !DemoFormSource::ENABLED
        row = ActiveRecord::Base.connection.select_one(<<~SQL)
          SELECT p.prosrc,
            EXISTS(SELECT 1 FROM pg_trigger t
              WHERE t.tgrelid='credis_demo_form_evidence'::regclass AND t.tgname='credis_demo_append_authority'
                AND t.tgfoid=p.oid AND t.tgtype=7 AND t.tgenabled='O' AND NOT t.tgisinternal) AS guarded,
            EXISTS(SELECT 1 FROM pg_attribute a
              WHERE a.attrelid='credis_demo_form_evidence'::regclass AND a.attname='append_authority'
                AND a.atttypid='jsonb'::regtype AND a.attnum>0 AND NOT a.attisdropped) AS typed
          FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace
          WHERE n.nspname=current_schema() AND p.proname='certify_credis_demo_form_append' AND p.pronargs=0
        SQL
        raise SourceCompatibility::Error, "Demo authority source guard unavailable" if !row || row["prosrc"].strip != SQL_BODY.strip || row["guarded"] != true || row["typed"] != true
        true
      rescue ActiveRecord::StatementInvalid
        raise SourceCompatibility::Error, "Demo authority source guard unavailable"
      end
    end
  end
end
